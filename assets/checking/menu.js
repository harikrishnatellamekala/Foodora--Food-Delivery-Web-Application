const CART_KEY = "spicefitCart";


function getCart() {

    try {

        const cart =
            JSON.parse(
                localStorage.getItem(CART_KEY)
            ) || [];

        return Array.isArray(cart)
            ? cart
            : [];

    } catch {

        return [];

    }

}


function saveCart(cart) {

    localStorage.setItem(
        CART_KEY,
        JSON.stringify(cart)
    );

    updateCartCount();

}


/* =====================================================
   CART COUNT
===================================================== */

function updateCartCount() {

    const cart =
        getCart();


    const count =
        cart.reduce(
            (total, item) => {

                return total +
                    Number(item.quantity || 0);

            },
            0
        );


    const cartCount =
        document.getElementById(
            "cartCount"
        );


    if (cartCount) {

        cartCount.textContent =
            count;

    }

}


updateCartCount();


/* =====================================================
   ADD TO CART
===================================================== */

document.addEventListener(
    "click",
    event => {

        const button =
            event.target.closest(
                ".add-button"
            );


        if (!button) return;


        const itemName =
            button.dataset.name;


        const price =
            Number(
                button.dataset.price
            );


        const image =
            button.dataset.image;


        if (
            !itemName ||
            !Number.isFinite(price)
        ) {

            console.error(
                "Invalid menu item:",
                button.dataset
            );

            return;

        }


        const cart =
            getCart();


        /*
           SAME ITEM + SAME RESTAURANT
           = quantity increase
        */

        const existing =
            cart.find(
                item =>
                    item.name === itemName &&
                    item.restaurant === restaurantName
            );


        if (existing) {

            existing.quantity =
                Number(
                    existing.quantity || 0
                ) + 1;

        } else {

            cart.push({

                name:
                    itemName,

                price:
                    price,

                quantity:
                    1,

                image:
                    image || "",

                description:
                    `Delicious ${itemName.toLowerCase()} prepared specially for you.`,

                restaurant:
                    restaurantName,

                location:
                    restaurant.location

            });

        }


        saveCart(cart);


        /* BUTTON FEEDBACK */

        button.textContent =
            "✓";


        button.classList.add(
            "added"
        );


        setTimeout(
            () => {

                button.textContent =
                    "+";

                button.classList.remove(
                    "added"
                );

            },
            700
        );

    }
);


